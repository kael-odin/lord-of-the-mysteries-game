// Ch20 是同路章（走，自己的，路，但不是，一个人走），
// Ch21 是各自章（走，自己的，路——同路一段，到此，各自，走）。
// 第五卷「行」的母题，在这里被推进到一个新的、更冷的、也更深的层：
// 走自己的路，不是，一个人走；可走自己的路，终究，是，自己，走。
// 椅子替你记你与同路人同走的那段路，也，开始，替你记你各自走的那段路——
// 这一程，没人与你同路，可椅子，仍，记你。
//
// 设计（变奏⑤）：
// - 入口：c20_hub「合上眼，顺印记，往各自那一段走·各自」→ c21_start。
//   c21_start 设 eachpath_pending。
// - 主线：与同路人在岔口分别后，你自走一条没走过的、第三条旧道——
//   Ch19 你走了自己选的那一条；Ch20 你与同路人同走了另一条；
//   Ch21 你，一个人，走剩下那一条。无人同路：自己看稳，自己扶自己，
//   自己，认完。在旧道深处遇一桩没散尽的余烬——这回，是一个人，
//   独自，认完（认完后，发现那余烬，其实，也记着「同走的人」）。
// - 三段「各自」的走（无聚合体 boss，无沉更深处管线）：
//   1) c21_walk：独自走一段新旧道（一个人走，自己替自己看稳）。
//   2) c21_shelter：独自守护一桩差事（一桩「一个人也能认完」的余烬）。
//   3) c21_end：在旧道尽头，自己，把第五卷第三页「各」「自」，凝定。
// - climax：c21_climax（灰雾之上·第十四次复命·各自走一段路·第五卷·转）。
//   第14铜币变奏：不是「替你记你与同路人同走的那段路」，
//   是「替你记你各自走的那段路」——椅子开始在你「各自走」的时候，
//   把你自己走的那段，也记着。可这一回，它记的，是「各自」——
//   同路一段之后，各自，走。
// - 新结局：eachpath（各自者·第十四桩差事是与同路人分别后各自走一段路，
//   塔罗会铜币第十四枚——「椅子替你记你各自走的那段路」）。
// - 新伏笔：第五卷第四页，留白——为下一程（各自走完，往何处去）留着。
//
// 第五卷母题转：行→同路→各自。走自己的路，不是，一个人走；
// 可走自己的路，终究，是，自己，走。塔罗会「不催路，只替你把路记得」
// 的原则，在这一章，被推进到「连你各自走的那段，也替你记」——
