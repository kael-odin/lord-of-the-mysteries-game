// ============ 第十七章 · 灰雾之上·忆归（第四卷·转）============
// 灰雾之上那册无名的书，翻到了第四卷的第三页。「忆」「归」两个字，
// 不再指向更深处——它指向，来处。塔罗会的第十桩差事，落在你身上时，
// 主位没有给你新的方向。祂只说：「这一程，不沉。往回，走。」
//
// 这是第四卷的转——结构性变奏章。前两章（Ch15 归念、Ch16 归名）是
// 「往更深处沉」的同构管线；这一章，第一次，不沉。所失之归，需以
// 「忆」归之——而「忆」，不是往更深的地方找，是，往回，走。
//
// 设计（变奏）：
// - 入口：c16_hub「合上眼，顺印记往回走·忆归」→ c17_start。
//   c17_start 设 memory_pending。c17_start → c17_recall（廷根·水仙花街）。
// - 主线：三段「忆」的回访（无聚合体 boss，无沉更深处管线）：
//   1) c17_recall：廷根·水仙花街（第一卷起点）→ 小判定 + 旧房东回声。
//   2) c17_company：黑荆棘公司 → 小判定 + 老尼尔/队长回声。
//   3) c17_bell：钟楼（第四卷钟绳旧事）→ 小判定 + 钟声回声。
// - climax：c17_climax（灰雾之上·第十次复命·无差事的一枚铜币）。
//   第10铜币变奏：不是「再沉一程得一枚」，是「无差事，也记你一枚」
//   ——椅子开始在你没有差事的时候，也替你记。这才是「忆归」真意。
// - 新结局：memorykeeper（守忆者·第十桩差事是无差事的一程，
//   塔罗会铜币第十枚——「椅子在你没有差事的时候，也替你记一枚」）。
// - 新伏笔：第四卷第四页「归」「处」——但这次的「归处」不再是
//   「该回哪儿」，而是「归处即此刻」。指向 Ch18。
//
// 第四卷母题转篇：归念→归名→忆归。所失之归，需以忆归之——而忆，
// 是往回走，不是往更深沉。塔罗会「不催路，只替你把路记得」的原则，
// 在这一章，被推进到「连你没在走路的时候，也替你记」——椅子不再
// 只在你沉更深处时记你，它开始，在你往回走、在你停、在你只是忆的
// 时候，也，记你。十枚铜币并排，第四卷，到这一页，转了一程。

