// 第五卷「行」的母题，在这里被推进：「走自己的路」不是孤立——
// 椅子替你记你自己走的路，也开始，替你记你与同路人同走的那段路。
//
// 设计（变奏④）：
// - 入口：c19_hub「合上眼，顺印记，往同路那一段走·同路」→ c20_start。
//   c20_start 设 samepath_pending。
// - 主线：在贝克兰德城外三里岔口，遇见一位同路人——
//   她是塔罗会另一张椅子上、被「椅子替你记她没走完的路」的人。
//   她走的是你 Ch19 没选的那两条旧道之一（玩家若 Ch19 走北，她走南；
//   若走南/东，她走另两条之一——由玩家在岔口认出她时，自选她走哪条）。
//   一起走一程同路：c20_meet（认出同路人）→ c20_walk（同走一段旧道）
//   → c20_shelter（共同守护一桩差事：一桩旧道上的「没散尽的余烬」，
//      两份余烬，要两个走同路的人，一起，认，才能认完）。
// - 三段「同」的走（无聚合体 boss，无沉更深处管线）：
//   1) c20_walk：同走一段旧道（一起走，互相替对方看一段没走稳的路）。
//   2) c20_shelter：共同守护一桩差事（一桩「两人才能认完」的余烬）。
//   3) c20_part：在岔口分别（同路一段，到此；各自的路，仍要各自走）。
// - climax：c20_climax（灰雾之上·第十三次复命·同走一段路·第五卷·承）。
//   第13铜币变奏：不是「替你记你自己走的路」，
//   是「替你记你与同路人同走的那段路」——椅子开始在你「与人同走」时，
//   把你们同走的那段，也记着。
// - 新结局：samepath（同路者·第十三桩差事是与同路人同走一段路，
//   塔罗会铜币第十三枚——「椅子替你记你与同路人同走的那段路」）。
// - 新伏笔：第五卷第二页「同」「路」——你与同路人，一起，写上的。
//   指向 Ch21（第五卷·转）。下一程「各自的路，仍要各自走」。
//
// 第五卷母题承：行→同路。走自己的路，不是，一个人走。
// 塔罗会「不催路，只替你把路记得」的原则，在这一章，被推进到
