// - 支线 1：arc_nameless（归名残名阁，一段关于「归名是锚」的旧事）。
// - 新结局：namekeeper（守归名者·第九桩差事办成，塔罗会铜币第九枚——
//   九枚铜币在塔罗会，意味着「椅子替你记归名，也开始替你认路」：
//   你与椅子，互为归名）。
// - 战斗敌人 name_culler / name_aspect 见 data.ts。
//
// 第四卷母题承篇：归念头→归名字。归念是「该回哪儿」，归名是
// 「我是谁的归人」——所归越深，所失越深。第二页「失归」，在这一章，
