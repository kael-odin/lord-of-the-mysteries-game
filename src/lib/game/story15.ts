// 灰雾之上那册无名的书，翻到了第四卷的第二页。「失」「归」两个字，
// 不再只是扉页的伏笔——它指向归墟更深处、那座半掩着无数「归名」的、
// 没人再「归于谁」的旧归名冢。塔罗会的第九桩差事，落在归名冢上。
// 归名派——归墟学派更深处的一支隐秘教派——把凡俗「归名」夺走、
// 让人「不再有归名」（不再记得自己是「谁的归人」、也不再有人
// 「归于自己」）、以此「免于有归名」的灰雾更深处隐秘教派——是
// 这一章的主线战场，也是第四卷「归念→归名→…」母题的第二环。
//
// 第四卷母题（承篇）：归。第三卷是「偷」（失），第四卷是「归」
// （归向何处）。归念是「该回哪儿」，归名是「我是谁的归人」——
// 比「归念」更深一寸。归名派信「无归名，无痛」：他们觉得，
// 人之所以苦，是因为「有归名」——有归名，就有牵，有牵，就有苦。
// 所以他们夺「归名」，让人「不再有归名」，以为这是，慈悲。
// 可他们不懂：无归名，不是不苦——是，连「我是谁的归人」，
// 都没人替你记。第二页伏笔「失」「归」，在这一章，揭示为：
// 所「归」之深，连「归名」都被磨平——是谓「失归」。
//
// 设计：
