//   c16_start 设 name_pending。c16_start → c16_gate（归名冢外·无名林）。
// - 主线：归名冢寻线索 → c16_inner（灵视/体魄 + reader/collector 扮演）
//   → c16_descent（旧归名冢腔）→ c16_name_aspect（归名聚合体战）
//   → c16_climax → c16_victory。
