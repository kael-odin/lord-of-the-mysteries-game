//   2) c27_shelter：在选定的地方，独自留一笔自己的。
//   3) c27_end：在那地方尽头，自己，把第七卷封皮空白，写下，第一笔。
// - climax：c27_climax（灰雾之下·第二十次复命·留下第一笔·第七卷·开）。
//   第20铜币变奏：不是「替你记你认出来的那颗心」，
//   是「替你记你留下来的那一笔」——椅子开始在你「留」的时候，
//   把你留下来的，记着。这一回，记的，是「留」，不是「认」。
