//
// 前六卷的母题是 守护→偷→归→此刻→行→认。守，是把不该被偷的，守住；偷，
// 是把被偷的，偷回来；归，是把归的，归；此刻，是把此刻，停成，归处；行，是
// 走自己的路；认，是把没被认出的，认出来。可守完、偷完、归完、停完、走完、
// 认完之后，灰雾里，仍，有，东西，没，被，留，下——不是没被守，不是没被偷回，
// 不是没被归，不是没被停成归处，不是没被走，不是没被认出，是，没，被，留，下。
// 第七卷不再问「守住什么」「认出什么」——第七卷问「留下什么」。
//
// 这是第七卷的开——第一个结构性变奏章。玩家从「认出灰雾里没被认出的」
// 转入「往灰雾里，留，一笔」。椅子替你记你走的路、你认出的那张脸、那个名字、
// 那个人、那颗心，也，开始，替你记，你，留下来的，那一笔。
