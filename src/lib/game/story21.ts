// 第五卷的第三页，「各」「自」两个字，是你，一个人，凝定的。
// 第四页，是，空白——比第一页，还白。
// 因为这一程，要由你，自己，往那空白上，写。
//
// 这是第五卷的合——第六个结构性变奏章。Ch17 是回声章（往回走），
// Ch18 是此刻章（停，在，此刻），Ch19 是行路章（走，自己的，路），
// Ch20 是同路章（走，自己的，路，但不是，一个人走），
// Ch21 是各自章（走，自己的，路——同路一段，到此，各自，走），
// Ch22 是自定章（走，自己的，路——各自走完，下一程往何处去，自己，定）。
// 第五卷「行」的母题，在这里被推进到最终的、最自由的、也最深的层：
// 走自己的路，不是，一个人走；可走自己的路，终究，是，自己，走；
// 而自己走，终究，是，自己，定，往何处走。
// 椅子替你记你自己走的路、你与同路人同走的那段、你各自走的那段，
// 也，开始，替你记你自己定的那段——这一程，主位把方向，交还，给你。
//
// 设计（变奏⑥）：
// - 入口：c21_hub「合上眼，顺印记，往自定那一段走·自定」→ c22_start。
//   c22_start 设 selfpath_pending。主位把第五卷第四页（空白）往玩家这边推一寸，
//   不指方向——"这一程，往何处去，由你，自己，定"。
// - 主线：玩家在岔口，自定往何处去（三选一，另两处留白待重走）：
//   ① 回廷根——水仙花街旧房东那段没散尽的、旧房租的、余声；
//   ② 去新地方——雾都东郊没去过的、旧煤气厂那片废铁的、余声；
//   ③ 留在岔口——旧路碑边老脚夫姓碑那段没散尽的、旧道的、余声。
//   无论选哪个，主位不指方向，只记玩家自己定的那段。
//   在选定的地方，独自认一桩自己定要认的余烬。
// - 三段「自定」的走（无聚合体 boss，无沉更深处管线）：
//   1) c22_choose：在岔口自定往何处去（一起走，互相替对方看一段没走稳的路）。
//   2) c22_shelter：在自己定要去的地方，独自认一桩自己定要认的余烬。
//   3) c22_end：在那地方尽头，自己，把第五卷第四页空白，写上。
// - climax：c22_climax（灰雾之上·第十五次复命·自定一段路·第五卷·合）。
//   第15铜币变奏：不是「替你记你各自走的那段路」，
//   是「替你记你自己定的那段路」——椅子开始在你「自己定」的时候，
//   把你定的那段，记着。这一回，主位把第五卷，合，上——
//   与第四卷 Ch18/c18_climax_next 合上呼应："下一卷方向由下一程差事自然给出"。
// - 新结局：selfpath（自定者·第十五桩差事是你自己定往何处去并认完一桩余烬，
//   塔罗会铜币第十五枚——「椅子替你记你自己定的那段路」）。
//
// 第五卷母题合：行→同路→各自→自定。走自己的路，最终，是，自己，定，
// 往何处去。塔罗会「不催路，只替你把路记得」的原则，在这一章，
// 被推进到「连你自己定的那段，也替你记」——椅子不再只在你
