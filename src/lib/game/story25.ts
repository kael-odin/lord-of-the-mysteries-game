// ============ 第二十六章 · 灰雾之下·认心（第六卷·合·变奏④·认心章）============
// 第六卷的第一页，是你，自己，认出第一笔，翻开的（Ch23）。
// 第二页，是你，自己，认名出第二笔，写上的（Ch24）。
