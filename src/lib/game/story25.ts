// 第四页，是，空白——比第三页，还白。主位说："认出没被叫出名字的、被忘了名字的、
// 被藏起来的，下一程认出什么，你，自己，看。"
// 这是第六卷的合——第四个、也是，最后一个，结构性变奏章。
// Ch23 是认章（认出没被叫出名字的），Ch24 是认名章（认出被忘了名字的），
// Ch25 是认人章（认出一个被藏起来的、人），Ch26 是认心章（认出一个被藏起来的、心）。
//
// 认，是把没被叫出名字的，叫出，名字（Ch23）。
// 认名，是把被忘了名字的，重新，叫出，名字（Ch24）。
// 认人，是把被藏起来的，人，认，出，来（Ch25）。
// 认心，是把被藏起来的，心，认，出，来（Ch26）——
// 不一样：Ch23 认的是东西的脸，Ch24 认的是东西的名字，Ch25 认的是一个人，
// Ch26 认的，是，一个人被藏起来的、心——他做的事里，藏着的那点，他自己，
// 也，认不出，的，心。认心，比认人，更深一寸：你认出的，不是被藏起来的人，
// 是，被藏起来的，一颗，心，本身。
//
// 第六卷母题合篇：认→认名→认人→认心。你认出了没被叫出名字的，也认出了被忘了名字的，
// 也认出了被藏起来的；这一程，你认出一个，被藏起来的，心。椅子替你记你认出来的那张脸、
// 那个名字、那个人，也，开始，替你记，你认出来的，那颗心——这一回，记的，是「心」，
// 比「人」更轻，也更深。
//
